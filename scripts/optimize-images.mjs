/**
 * Generates right-sized menu images from the sources in `assets-source/menu`.
 *
 * Output
 *   public/images/menu/<name>-<width>.webp   (400 / 640 / 960 px wide)
 *   src/data/menu-image-blur.generated.ts    (tiny blur-up placeholders)
 *
 * The 1200px sources weigh 60–165 KB each; a card only ever shows ~300 px, so
 * serving a 400/640 px variant cuts a typical card image to 10–30 KB.
 *
 * Usage:  npm run build:images
 */
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE_DIR = path.join(ROOT, "assets-source", "menu");
const OUT_DIR = path.join(ROOT, "public", "images", "menu");
const BLUR_FILE = path.join(ROOT, "src", "data", "menu-image-blur.generated.ts");
const WIDTHS = [400, 640, 960];

await rm(OUT_DIR, { recursive: true, force: true });
await mkdir(OUT_DIR, { recursive: true });

const blur = {};
const files = (await readdir(SOURCE_DIR)).filter((f) => /\.(webp|jpe?g|png)$/i.test(f)).sort();

for (const file of files) {
  const name = path.parse(file).name.toLowerCase();
  const source = sharp(path.join(SOURCE_DIR, file));
  const { width = 0 } = await source.metadata();

  for (const w of WIDTHS) {
    await source
      .clone()
      .resize({ width: Math.min(w, width), withoutEnlargement: true })
      .webp({ quality: 72, effort: 5 })
      .toFile(path.join(OUT_DIR, `${name}-${w}.webp`));
  }

  const tiny = await source.clone().resize({ width: 10 }).webp({ quality: 40 }).toBuffer();
  blur[name] = `data:image/webp;base64,${tiny.toString("base64")}`;
}

const body = Object.entries(blur)
  .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
  .join("\n");

await writeFile(
  BLUR_FILE,
  `// AUTO-GENERATED by scripts/optimize-images.mjs — do not edit by hand.\n` +
    `export const MENU_IMAGE_BLUR: Record<string, string> = {\n${body}\n};\n`,
);

console.log(`Optimized ${files.length} images × ${WIDTHS.length} sizes → public/images/menu`);
